"""Таблицы результатов в README обновляются только скриптом.

Каждая таблица живёт между маркерами ``<!-- BEGIN name -->`` и
``<!-- END name -->``. ``eval.py`` подставляет туда то, что записали
``evals/retrieval_eval.py`` и ``evals/answer_eval.py``, — цифр, набранных
руками, в README нет.
"""

from __future__ import annotations

import re
from collections import Counter

from kz_labor_rag.eval.dataset import QUESTION_TYPES, EvalDataset


class MissingBlockError(ValueError):
    """В README нет маркеров для блока."""


def replace_block(text: str, name: str, content: str) -> str:
    # Содержимого между маркерами может и не быть: в свежем README они стоят вплотную.
    pattern = re.compile(
        rf"(<!-- BEGIN {re.escape(name)} -->\n)(?:.*?\n)?(<!-- END {re.escape(name)} -->)", re.S
    )
    if not pattern.search(text):
        raise MissingBlockError(f"в README нет блока {name}")
    return pattern.sub(lambda m: f"{m.group(1)}{content.strip()}\n{m.group(2)}", text, count=1)


def strip_generated_comment(table: str) -> str:
    """Убрать служебную строку ``<!-- generated by ... -->`` из файла таблицы."""
    return "\n".join(
        line for line in table.splitlines() if not line.startswith("<!-- generated")
    ).strip()


def dataset_summary(dataset: EvalDataset) -> str:
    ready = dataset.ready
    verified = dataset.verified
    by_type = Counter(q.type for q in ready)
    verified_by_type = Counter(q.type for q in verified)
    by_human = sum(1 for q in verified if q.verified_by == "human")
    by_model = sum(1 for q in verified if q.verified_by == "model")
    checked = [q for q in ready if q.human_check]
    confirmed = sum(1 for q in checked if q.human_check == "confirmed")
    lines = [
        f"{len(ready)} questions in `evals/questions.jsonl`: "
        f"{sum(1 for q in ready if not q.is_unanswerable)} answerable, "
        f"{sum(1 for q in ready if q.is_unanswerable)} unanswerable; "
        f"{sum(1 for q in ready if q.origin == 'real')} real user questions, "
        f"{sum(1 for q in ready if q.origin == 'synthetic')} written for this set. "
        f"**{len(verified)} verified** — metrics are computed on these only: "
        f"{by_human} checked by hand, {by_model} by a model-assisted review pass. "
        f"Random spot check of the model-reviewed questions by hand: "
        f"{confirmed} of {len(checked)} confirmed.",
        "",
        "| type | questions | verified |",
        "|---|---|---|",
    ]
    lines += [f"| {t} | {by_type[t]} | {verified_by_type[t]} |" for t in QUESTION_TYPES]
    return "\n".join(lines)
