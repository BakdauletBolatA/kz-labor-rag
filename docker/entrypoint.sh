#!/usr/bin/env bash
# Точка входа контейнера api.
#
# Делает то, что иначе пришлось бы делать руками после `docker compose up`:
# добывает корпус, проверяет контрольную сумму и строит индекс, если его нет.
# Каждый шаг логируется и пропускается, если уже сделан, поэтому повторный
# запуск дёшев.
set -euo pipefail

RAW_FILE="data/raw/adilet_K1500000414_rus.html"
SOURCE_URL="https://adilet.zan.kz/rus/docs/K1500000414"
CHECKSUM_FILE="data/raw/CHECKSUM"

log() { printf '[entrypoint] %s\n' "$*"; }

# --- 1. корпус ---------------------------------------------------------------
mkdir -p data/raw
if [ ! -s "$RAW_FILE" ]; then
  log "Корпус не найден, скачиваю с adilet.zan.kz (в репозиторий он не коммитится)"
  curl -sS -L --max-time 300 --compressed --retry 3 --retry-delay 5 \
    -A "Mozilla/5.0 (compatible; kz-labor-rag/0.1)" \
    -o "$RAW_FILE" "$SOURCE_URL" \
    || { log "ОШИБКА: не удалось скачать корпус. Положите файл в $RAW_FILE вручную."; exit 1; }
  log "Скачано: $(wc -c < "$RAW_FILE") байт"
else
  log "Корпус на месте: $RAW_FILE"
fi

# Контрольная сумма — предупреждение, а не отказ: adilet публикует новые
# редакции, и это законный повод отличаться. Но знать об этом надо, потому
# что метрики между редакциями несравнимы.
if [ -f "$CHECKSUM_FILE" ]; then
  if sha256sum -c "$CHECKSUM_FILE" >/dev/null 2>&1; then
    log "Контрольная сумма корпуса совпала с зафиксированной в SOURCE.md"
  else
    log "ВНИМАНИЕ: корпус отличается от зафиксированного в data/raw/SOURCE.md."
    log "          Скорее всего вышла новая редакция. Метрики, посчитанные на"
    log "          разных редакциях, между собой несравнимы — обновите SOURCE.md"
    log "          и переиндексируйте осознанно."
  fi
fi

# --- 2. индекс ---------------------------------------------------------------
if [ "${KZRAG_SKIP_INDEX:-0}" = "1" ]; then
  log "KZRAG_SKIP_INDEX=1 — построение индекса пропущено"
else
  if kzrag-index status >/dev/null 2>&1; then
    log "Индекс уже построен и соответствует конфигу"
  else
    log "Строю индекс. Первый запуск тянет веса модели и кодирует корпус на CPU —"
    log "это занимает несколько минут. Результат кэшируется и переживает рестарт."
    kzrag-index build || { log "ОШИБКА: индекс построить не удалось"; exit 1; }
  fi
fi

log "Запускаю: $*"
exec "$@"
