def build_answerable(by_number: dict) -> list[EvalQuestion]:
    out = []
    for qid, text, qtype, tags, anchors, acceptable in ANSWERABLE:
        evidence, clauses = [], {}
        for article, anchor in anchors:
            quote = extract_evidence(by_number[article].full_text, anchor)
            if not any(e["quote"] == quote for e in evidence):
                evidence.append({"article": article, "quote": quote})
            pairs = [(c.number, c.text) for c in by_number[article].clauses]
            for number in clauses_of_quote(pairs, quote):
                clauses[(article, number)] = None
        out.append(
            EvalQuestion.from_dict(
                {
                    "id": qid,
                    "question": text,
                    "lang": "ru",
                    "origin": "synthetic",
                    "type": qtype,
                    "required_articles": list(dict.fromkeys(a for a, _ in anchors)),
                    "required_clauses": [{"article": a, "clause": c} for a, c in clauses],
                    "acceptable_articles": acceptable,
                    "evidence": evidence,
                    "tags": tags,
                },
                source=qid,
            )
        )
    return out


def build_unanswerable() -> list[EvalQuestion]:
    return [
        EvalQuestion.from_dict(
            {
                "id": qid,
                "question": text,
                "lang": "ru",
                "origin": "synthetic",
                "type": "unanswerable",
                "notes": notes,
                "tags": ["вне-кодекса"],
            },
            source=qid,
        )
        for qid, text, notes in UNANSWERABLE
    ]


def main() -> int:
    code = parse_file(RAW)
    existing = load_dataset(PATH)
    known = {q.id for q in existing.questions}
    new = [
        q
        for q in build_answerable(code.by_number) + build_unanswerable()
        if q.id not in known
    ]
    if not new:
        print("Все вопросы уже добавлены.")
        return 0

    new = [replace(q, verified=True, verified_by="model", split="test") for q in new]
    old = tuple(replace(q, split="dev") if q.split is None else q for q in existing.questions)
    dataset = EvalDataset(questions=old + tuple(new))
    report = validate_against_corpus(
        dataset, code.article_texts(), {a.number: a.clause_numbers for a in code}
    )
    if not report.ok:
        print(f"Разметка не сходится с корпусом: {report}", file=sys.stderr)
        return 1
    save_dataset(dataset, PATH)
    print(f"Добавлено {len(new)} вопросов; всего {len(dataset.ready)}.")
    return 0


