# Пятнадцать слотов под реальные формулировки с форумов кадровиков.
# Лежат в том же файле, что и готовые вопросы, но со status='draft':
# так видно, сколько ещё осталось, и при этом гейт их не засчитывает.
REAL_SLOTS = 15


def extract_evidence(article_text: str, anchor: str, *, max_len: int = 400) -> str:
    """Вырезать из текста статьи дословный фрагмент вокруг якоря.

    Границы расширяются до начала и конца предложения, чтобы цитата читалась
    сама по себе. Возвращается именно подстрока исходного текста — ни одного
    символа не дописывается.
    """
    pos = article_text.find(anchor)
    if pos < 0:
        raise ValueError(f"якорь не найден в тексте статьи: {anchor!r}")

    left = max(
        article_text.rfind(". ", 0, pos) + 2,
        article_text.rfind("\n", 0, pos) + 1,
        0,
    )
    end_match = re.search(r"[.;]\s", article_text[pos + len(anchor) :])
    right = pos + len(anchor) + (end_match.end() - 1 if end_match else 0)

    fragment = article_text[left:right].strip()
    if len(fragment) > max_len:
        fragment = article_text[pos : pos + max_len].strip()
    return fragment


def write_review(dataset: EvalDataset, code) -> None:
    """Собрать таблицу для ревью человеком.

    Ревью идёт по дословной цитате: видно, из какой нормы взят эталон, не
    открывая кодекс. Файл генерируется, а не правится руками, — иначе он
    разъедется с датасетом.
    """
    by_number = code.by_number
    lines = [
        "# Ревью разметки синтетических вопросов",
        "",
        "Файл сгенерирован `scripts/build_synthetic_dataset.py`. Руками не править.",
        "",
        "Проверять нужно одно: следует ли ответ на вопрос из процитированной нормы,",
        "и не пропущена ли статья, без которой ответ неполон. Цитаты вырезаны из",
        "распарсенного текста кодекса дословно — выдумать их скрипт не может.",
        "",
        f"Редакция корпуса: **{code.edition_date}**.",
        "",
    ]
    ready = sorted(dataset.ready, key=lambda q: q.id)
    for tag in dict.fromkeys(t for q in ready for t in q.tags):
        lines += [f"## {tag}", ""]
        for q in (x for x in ready if tag in x.tags):
            arts = ", ".join(f"ст. {n}" for n in q.required_articles)
            titles = "; ".join(
                by_number[n].title for n in q.required_articles if n in by_number
            )
            lines.append(f"### {q.id} — {arts}")
            lines.append("")
            lines.append(f"**Вопрос:** {q.question}")
            lines.append("")
            lines.append(f"**Обязательные статьи:** {arts} — {titles}")
            if q.acceptable_articles:
                lines.append("")
                lines.append(
                    "**Допустимые (не штрафуются):** "
                    + ", ".join(f"ст. {n}" for n in q.acceptable_articles)
                )
            if q.preferred_clause:
                lines.append("")
                lines.append(f"**Точный пункт:** {q.preferred_clause}")
            lines.append("")
            lines.append(f"> {q.evidence}")
            if q.notes:
                lines.append("")
                lines.append(f"*{q.notes}*")
            lines += ["", "---", ""]

    drafts = [q.id for q in dataset if q.is_draft]
    lines += [
        "## Слоты под реальные вопросы",
        "",
        f"Зарезервировано {len(drafts)} слотов: `{drafts[0]}`…`{drafts[-1]}`.",
        "Они лежат в датасете со `status: draft`, в метриках не участвуют и",
        "гейтом укомплектованности не засчитываются.",
        "",
    ]
    Path(REVIEW).write_text("\n".join(lines) + "\n", encoding="utf-8")


def main() -> int:
    code = parse_file(RAW)
    by_number = code.by_number
    repealed = {a.number for a in code if a.is_repealed}

    questions: list[EvalQuestion] = []
    problems: list[str] = []

    for qid, text, required, acceptable, preferred, tags, (ev_article, anchor), notes in SPECS:
        for num in list(required) + list(acceptable):
            if num not in by_number:
                problems.append(f"{qid}: статьи {num} нет в кодексе")
            elif num in repealed:
                problems.append(f"{qid}: статья {num} исключена из кодекса")

        if ev_article not in required:
            problems.append(f"{qid}: цитата взята из статьи {ev_article}, которой нет в required")

        try:
            evidence = extract_evidence(by_number[ev_article].full_text, anchor)
        except (KeyError, ValueError) as exc:
            problems.append(f"{qid}: {exc}")
            continue

        if preferred is not None:
            art, clause = preferred
            if clause not in by_number[art].clause_numbers:
                problems.append(
                    f"{qid}: у статьи {art} нет пункта {clause} "
                    f"(есть: {', '.join(by_number[art].clause_numbers)})"
                )

        questions.append(
            EvalQuestion.from_dict(
                {
                    "id": qid,
                    "question": text,
                    "origin": "synthetic",
                    "source_url": None,
                    "required_articles": list(required),
                    "acceptable_articles": list(acceptable),
                    "preferred_clause": (
                        None
                        if preferred is None
                        else {"article": preferred[0], "clause": preferred[1]}
                    ),
                    "tags": list(tags),
                    "lang": "ru",
                    "evidence": evidence,
                    "status": "ready",
                    "reviewed_by_human": False,
                    "notes": notes,
                }
            )
        )

    # Лимит на тему: без него датасет незаметно съезжает в увольнения.
    from collections import Counter

    per_tag = Counter(tag for q in questions for tag in q.tags)
    for tag, count in per_tag.items():
        if count > MAX_PER_TAG:
            problems.append(f"тема '{tag}': {count} вопросов, максимум {MAX_PER_TAG}")

    slots = [
        EvalQuestion.from_dict(
            {"id": f"real_{i:03d}", "lang": "ru", "origin": "real", "status": "draft"}
        )
        for i in range(1, REAL_SLOTS + 1)
    ]

    dataset = EvalDataset(questions=tuple(questions) + tuple(slots))
    report = validate_against_corpus(
        dataset,
        code.article_texts(),
        {a.number: a.clause_numbers for a in code},
    )
    problems += [f"{qid}: цитата не найдена в тексте обязательных статей" for qid in report.quote_not_found]
    problems += [f"{qid}: {ref} — такого пункта нет" for qid, ref in report.missing_clauses]

    if problems:
        print("Сборка остановлена, проблемы разметки:", file=sys.stderr)
        for p in problems:
            print(f"  - {p}", file=sys.stderr)
        return 1

    save_dataset(dataset, OUT)
    write_review(dataset, code)
    print(f"Записано: {OUT}")
    print(f"Записано: {REVIEW}")
    print(f"  готовых вопросов : {len(questions)}")
    print(f"  черновых слотов  : {len(slots)}")
    print("\nПо темам:")
    for tag, count in sorted(per_tag.items(), key=lambda kv: -kv[1]):
        print(f"  {tag:22} {count}")
    multi = [q.id for q in questions if len(q.required_articles) > 1]
    print(f"\nМногосоставных (эталон из связки статей): {len(multi)} — {', '.join(multi)}")
    print(f"С preferred_clause: {sum(1 for q in questions if q.preferred_clause)}")
    return 0


